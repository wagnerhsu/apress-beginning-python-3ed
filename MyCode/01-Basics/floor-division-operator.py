# Using floor division with integers
a = 10
b = 3
result = a // b
print("Floor Division Result:", result)  # Output: 3

# Floor division with negative numbers
a = -10
b = 3
result = a // b
print("Floor Division Result:", result)  # Output: -4

# Using floor division with floating point numbers
a = 10.5
b = 2
result = a // b
print("Floor Division Result:", result)  # Output: 5.0